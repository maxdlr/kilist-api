const toItems = (entries: Entry[]): FoodBankItem[] =>
  entries.map(([name, options = {}]) => ({
    name,
    icon: findFoodIcon(name),
    ...(!options.extra && !options.group && { staple: true }),
    ...(options.tags && { tags: options.tags }),
    ...(options.group && { group: options.group }),
  }));

